#include <bits/stdc++.h>
using namespace std;

int main() {
    int T;
    cin >> T;

    while (T--) {
        int X;
        cin >> X;

        if (X >= 30)
            cout << "YES" << endl;
        else
            cout << "NO" << endl;
    }

    return 0;
}
